-- Vérification publique d'un lot (traçabilité) : n'expose que des informations non sensibles.
create or replace function public.verify_lot(p_lot_number text)
returns table (
  lot_number text, species text, variety text, category text,
  certification_date date, germination_rate numeric, status text, campaign text
)
language sql
stable
security definer set search_path = public
as $$
  select l.lot_number, l.species, l.variety, l.category,
         l.certification_date, l.germination_rate, l.status, c.name
  from public.seed_lots l
  join public.campaigns c on c.id = l.campaign_id
  where upper(l.lot_number) = upper(trim(p_lot_number))
  limit 1;
$$;

grant execute on function public.verify_lot(text) to anon, authenticated;

